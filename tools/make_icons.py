def stroke(d, w=2):
    return f'    <path android:pathData="{d}" android:strokeColor="#FFFFFFFF" android:strokeWidth="{w}" android:strokeLineCap="round" android:strokeLineJoin="round" />\n'


def fill(d):
    return f'    <path android:pathData="{d}" android:fillColor="#FFFFFFFF" />\n'


def dot(cx, cy, r):
    return fill(f"M{cx - r},{cy}a{r},{r} 0 1 0 {2 * r},0a{r},{r} 0 1 0 {-2 * r},0Z")



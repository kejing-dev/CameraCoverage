# 3D icon layers + 512 export (PIL)
try:
    from PIL import Image, ImageDraw
except ImportError:
    print("drawables written; PIL missing, no PNG layers")
    sys.exit(0)

S = 1024
K = S / 108.0
GREEN = (11, 74, 52, 255)
CONE = (143, 240, 182, 255)
WHITE = (255, 255, 255, 255)
RED = (255, 59, 48, 255)


def tile():
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    ImageDraw.Draw(im).rounded_rectangle((40, 40, S - 40, S - 40), radius=220, fill=GREEN)
    return im


def glyph(with_cone=True, bg=None):
    im = Image.new("RGBA", (S, S), bg or (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    if with_cone:
        d.polygon([(50 * K, 47 * K), (88 * K, 30 * K), (88 * K, 74 * K)], fill=CONE)
        d.ellipse(((77.5 - 4) * K, (47 - 4) * K, (77.5 + 4) * K, (47 + 4) * K), fill=GREEN)
        d.pieslice(((72) * K, (54) * K, (83) * K, (70) * K), 180, 360, fill=GREEN)
    d.rounded_rectangle((20 * K, 36 * K, 58 * K, 40 * K), radius=2 * K, fill=WHITE)
    d.rounded_rectangle((24 * K, 41 * K, 56 * K, 53 * K), radius=4 * K, fill=WHITE)
    d.rectangle((54 * K, 43 * K, 58 * K, 51 * K), fill=WHITE)
    d.rectangle((37 * K, 53 * K, 41 * K, 63 * K), fill=WHITE)
    d.rounded_rectangle((29 * K, 63 * K, 49 * K, 67 * K), radius=2 * K, fill=WHITE)
    d.ellipse(((30 - 2.4) * K, (47 - 2.4) * K, (30 + 2.4) * K, (47 + 2.4) * K), fill=RED)
    return im


def alpha_white(im):
    w = Image.new("RGBA", im.size, (255, 255, 255, 0))
    w.putalpha(im.split()[3])
    return w


l0, l1 = tile(), glyph()
l0.save(os.path.join(DRAW, "icon_3d_layer_0.png"))
l1.save(os.path.join(DRAW, "icon_3d_layer_1.png"))
alpha_white(l0).save(os.path.join(DRAW, "icon_3d_sdf_0.png"))
alpha_white(l1).save(os.path.join(DRAW, "icon_3d_sdf_1.png"))
if len(sys.argv) > 1:
    full = Image.new("RGBA", (S, S), GREEN)
    Image.alpha_composite(full, l1).resize((512, 512), Image.LANCZOS).save(sys.argv[1])
print("icons written")
